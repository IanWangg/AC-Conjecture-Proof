"""TH19 checks of TH06.
(1) l(AK(n)) = Nielsen-instruction distance of the exponent matrix to I (E's 7 Nielsen instructions), n = 1..4.
(2) Brute-force test of TH06 Lemma 1.1 in finite 2-generated nilpotent groups G = <a,b> <= UT_n(F_2):
    for every e in gamma_2(G) there are g, g' with (a^g b)^{g'} b^-1 = a e, i.e. a e b is conjugate to an element of Cl(a) b.
    Also for the second pair (p,q) = (b, a e0) used in Theorem 1, and a control in S_4 (not nilpotent)."""
import sys, itertools, random
from collections import deque
# ---------- (1)
def ell(M):
    I = ((1, 0), (0, 1))
    def nb(M):
        (a, b), (c, d) = M
        yield ((-a, -b), (c, d)); yield ((a, b), (-c, -d)); yield ((c, d), (a, b))
        yield ((a+c, b+d), (c, d)); yield ((a-c, b-d), (c, d)); yield ((a, b), (c+a, d+b)); yield ((a, b), (c-a, d-b))
    seen = {M: 0}; dq = deque([M])
    while dq:
        X = dq.popleft()
        if X == I: return seen[X]
        for Z in nb(X):
            if Z not in seen and max(abs(e) for r in Z for e in r) <= 12:
                seen[Z] = seen[X] + 1; dq.append(Z)
print("(1) l(AK(n)), n=1..4:", [ell(((n, -(n+1)), (1, -1))) for n in range(1, 5)], "(TH06/E: 3, 4, 5, 6)")
# ---------- (2) unitriangular matrices over F_2 as tuples of row bitmasks
def mk(n, ones):
    rows = [1 << i for i in range(n)]
    for (i, j) in ones: rows[i] |= 1 << j
    return tuple(rows)
def mul(A, B):
    out = []
    for r in A:
        acc = 0; i = 0
        while r:
            if r & 1: acc ^= B[i]
            r >>= 1; i += 1
        out.append(acc)
    return tuple(out)
def closure(gens, mulf):
    S = set(gens); fr = list(gens)
    while fr:
        nx = []
        for g in fr:
            for h in gens:
                k = mulf(g, h)
                if k not in S: S.add(k); nx.append(k)
        fr = nx
    return S
def test(name, a, b, mulf, one):
    G = closure([a, b], mulf)
    inv = {}
    for g in G:
        # inverse by powering (finite group)
        h = g; prev = one
        while h != one: prev = h; h = mulf(h, g)
        inv[g] = prev
    comm = lambda g, h: mulf(mulf(inv[g], inv[h]), mulf(g, h))
    Gl = list(G)
    g2 = closure(list({comm(g, h) for g in (a, b) for h in Gl} | {one}), mulf)   # gamma_2 = normal closure of [a,b]: generated by [a,h],[b,h]
    conj = lambda u, g: mulf(mulf(inv[g], u), g)
    def lemma(p, q):
        Clp_q = {mulf(conj(p, g), q) for g in Gl}
        bad = 0
        for e in g2:
            t = mulf(mulf(p, e), q)
            if not any(conj(t, g) in Clp_q for g in Gl): bad += 1
        return bad
    random.seed(7); e0 = random.choice(list(g2))
    print(f"(2) {name}: |G|={len(G)}, |gamma_2|={len(g2)}; failures for (p,q)=(a,b): {lemma(a, b)};"
          f" for (p,q)=(b, a*e0): {lemma(b, mulf(a, e0))}")
n = 6
J = [(i, i+1) for i in range(n-1)]
test("UT_6(F_2), a=Jordan block, b=I+E12", mk(n, J), mk(n, [(0, 1)]), mul, mk(n, []))
test("UT_6(F_2), a=I+E12+E34+E56, b=I+E23+E45+E13", mk(n, [(0, 1), (2, 3), (4, 5)]), mk(n, [(1, 2), (3, 4), (0, 2)]), mul, mk(n, []))
n = 7
J = [(i, i+1) for i in range(n-1)]
test("UT_7(F_2), a=Jordan block, b=I+E23+E56", mk(n, J), mk(n, [(1, 2), (4, 5)]), mul, mk(n, []))
pm = lambda p, q: tuple(q[i] for i in p)   # permutations as tuples; control: S_4 = <(0 1 2 3), (0 1)> is not nilpotent
test("control S_4 (not nilpotent; the lemma is not claimed)", (1, 2, 3, 0), (1, 0, 2, 3), pm, (0, 1, 2, 3))
