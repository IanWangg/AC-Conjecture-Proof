"""Lift a packed orbit path without swapping the actual relators.

The carried coordinate map accounts for permutation and inversion in the
search key. Every emitted operation is a strict ordinary AC primitive.
The input is the checkpoint generated by packed_peak_search.cpp.
"""
import argparse
import json
import mmap
from pathlib import Path
import struct
from elementary_verify import inverse, reduce, replay


def pack(w):
    return sum('xXyY'.index(c) << (2*i) for i,c in enumerate(w))


def canonical(a, b):
    aa = len(a), min(pack(a), pack(inverse(a)))
    bb = len(b), min(pack(b), pack(inverse(b)))
    if aa > bb:
        aa, bb = bb, aa
    return aa[1] | bb[1] << (2*aa[0]) | aa[0] << 54 | bb[0] << 59


def unpack(key):
    a, b = (key >> 54) & 31, (key >> 59) & 31
    return [''.join('xXyY'[(key >> (2*i)) & 3] for i in range(a)),
            ''.join('xXyY'[(key >> (2*(a+i))) & 3] for i in range(b))]


def rotations(w):
    return [w[i:]+w[:i] for i in range(len(w))]


def lift(path, n, requested):
    state = ['x'*n+'Y'*(n+1), 'xyxYXY']
    moves = []

    def emit(op, i, **kw):
        moves.append(dict(op=op, i=i, **kw))
        if op == 'invert':
            state[i] = inverse(state[i])
        elif op == 'multiply':
            state[i] = reduce(state[i]+state[kw['j']])
        else:
            state[i] = reduce(kw['g']+state[i]+inverse(kw['g']))

    def coordinates(words):
        for perm in ((0,1), (1,0)):
            signs = []
            for i,j in enumerate(perm):
                if state[j] == words[i]:
                    signs.append(0)
                elif inverse(state[j]) == words[i]:
                    signs.append(1)
                else:
                    break
            if len(signs) == 2:
                return perm, signs
        raise AssertionError('state is not the recorded inversion/permutation orbit')

    assert path[0][1] == 255
    coordinates(path[0][0])
    for previous, (words, edge) in zip(path, path[1:]):
        perm, signs = coordinates(previous[0])
        if edge < 8:
            i, pair_signs = divmod(edge, 4)
            sa, sb = divmod(pair_signs, 2)
            recipient, donor = perm[i], perm[1-i]
            if signs[i] != sa:
                emit('invert', recipient)
            change_donor = signs[1-i] != sb
            if change_donor:
                emit('invert', donor)
            emit('multiply', recipient, j=donor)
            if change_donor:
                emit('invert', donor)
        else:
            assert edge < 16
            i, g = divmod(edge-8, 4)
            emit('conjugate', perm[i], g='xXyY'[g])
        coordinates(words)
    # The endpoint order is carried from the original tuple. Choose the
    # corresponding requested order, without silently swapping it.
    options = []
    for order in (requested, requested[::-1]):
        plan = []
        for actual, desired in zip(state, order):
            alternatives = []
            for flip in (0,1):
                w = inverse(actual) if flip else actual
                for k, rotated in enumerate(rotations(w)):
                    if rotated == desired:
                        alternatives.append((flip+k, flip, w[:k]))
            if not alternatives:
                break
            plan.append(min(alternatives))
        if len(plan) == 2:
            options.append((sum(item[0] for item in plan), order, plan))
    _, target, plan = min(options)
    for i, (_, flip, prefix) in enumerate(plan):
        if flip:
            emit('invert', i)
        for g in prefix:
            emit('conjugate', i, g=g.swapcase())
    assert state == target
    cert = {'format':'ordinary-ac-elementary-v1',
            'start':['x'*n+'Y'*(n+1),'xyxYXY'], 'target':target,
            'moves':moves, 'scope':'Explicit packed-checkpoint lift; no free-basis claim'}
    return cert, replay(cert)


def run(checkpoint, requested):
    keys = {canonical(a,b) for a in rotations(requested[0]) for b in rotations(requested[1])}
    with Path(checkpoint).open('rb') as file, mmap.mmap(file.fileno(), 0, access=mmap.ACCESS_READ) as data:
        magic,n,cap,processed,count = struct.unpack_from('=QIIQQ', data)
        assert magic == 0x41435041434b3031 and processed == count
        assert len(data) == 32+13*count
        candidates = []
        for index, (key,) in enumerate(struct.iter_unpack('=Q', memoryview(data)[32:32+8*count])):
            if key in keys:
                candidates.append(index)
        assert candidates
        best = None
        for index in candidates:
            path, current = [], index
            while True:
                key, = struct.unpack_from('=Q', data, 32+8*current)
                edge = data[32+12*count+current]
                path.append((unpack(key), edge))
                parent, = struct.unpack_from('=I', data, 32+8*count+4*current)
                if edge == 255:
                    assert current == parent == 0
                    break
                assert parent < current
                current = parent
            path.reverse()
            cert, result = lift(path, n, requested)
            rank = result['peak_total_length'], result['moves'], index
            if best is None or rank < best[0]:
                best = rank, cert, result, len(path)-1
    rank, cert, result, orbit_edges = best
    assert result['peak_total_length'] <= cap
    return cert, dict(status='PASS', ordinary_AC_goal_solved=False,
                      checkpoint_states=count, checkpoint_cap=cap,
                      rotation_orbit_keys_found=len(candidates),
                      selected_checkpoint_index=rank[2], orbit_path_edges=orbit_edges,
                      strict_replay=result, normalization_swaps_emitted=0)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('checkpoint')
    parser.add_argument('first')
    parser.add_argument('second')
    parser.add_argument('--certificate', required=True)
    parser.add_argument('--output', required=True)
    args = parser.parse_args()
    cert, result = run(args.checkpoint, [args.first, args.second])
    Path(args.certificate).write_text(json.dumps(cert, indent=2)+'\n')
    Path(args.output).write_text(json.dumps(result, indent=2)+'\n')
    print(json.dumps(result, indent=2))
