#!/usr/bin/env python3
"""TH20 independent computation of stabilizers in Out(F2) = GL2(Z) of cyclic words (up to inversion
or not), by the Whitehead level graph (McCool): vertices = minimal cyclic words of the Aut-orbit,
edges = signed permutations and transvections x->xy^{+-1}, y->yx^{+-1} that keep the length;
the stabilizer is generated by the Schreier loops.  Own code; rests on Whitehead/McCool (recalled)."""
import sys, itertools
sys.dont_write_bytecode = True
from th20_lib import red, inv, cyc, aut

def canon(w, up_to_inverse):
    w = cyc(w); c = [w[i:] + w[:i] for i in range(len(w))]
    if up_to_inverse: v = inv(w); c += [v[i:] + v[:i] for i in range(len(v))]
    return min(c)
GENS = []
for a, b in (("x", "y"), ("y", "x")):
    for sa in (0, 1):
        for sb in (0, 1):
            GENS.append({"x": inv(a) if sa else a, "y": inv(b) if sb else b})
GENS += [{"x": "xy", "y": "y"}, {"x": "xY", "y": "y"}, {"x": "x", "y": "yx"}, {"x": "x", "y": "yX"}]
def compose(g, h):   # (g o h)(letter) = g(h(letter))
    return {k: aut(g, h[k]) for k in "xy"}
def inverse_aut(g):
    # brute force: search the inverse among short automorphisms via matrix inverse + check
    M = mat(g); d = M[0][0] * M[1][1] - M[0][1] * M[1][0]
    raise NotImplementedError
def mat(g):
    e = lambda w: (w.count("x") - w.count("X"), w.count("y") - w.count("Y"))
    (a, c), (b, d) = e(g["x"]), e(g["y"])
    return ((a, b), (c, d))                 # columns = images of x, y
def mmul(A, B): return tuple(tuple(sum(A[i][k] * B[k][j] for k in range(2)) for j in range(2)) for i in range(2))
def minv(A):
    d = A[0][0] * A[1][1] - A[0][1] * A[1][0]
    return ((A[1][1] * d, -A[0][1] * d), (-A[1][0] * d, A[0][0] * d))
def stabilizer(w, up_to_inverse):
    w0 = cyc(w); M0 = ((1, 0), (0, 1))
    while True:                      # greedy descent to a Whitehead-minimal word, w0 = alpha(w), M0 = [alpha]
        for g in GENS:
            u = cyc(aut(g, w0))
            if len(u) < len(w0): w0 = u; M0 = mmul(mat(g), M0); break
        else: break
    w0 = canon(w0, up_to_inverse); L = len(w0)
    rep = {w0: ((1, 0), (0, 1))}; queue = [w0]; gens = set()
    while queue:
        v = queue.pop()
        for g in GENS:
            u = cyc(aut(g, v))
            if len(u) != L: continue
            u = canon(u, up_to_inverse); M = mmul(mat(g), rep[v])
            if u not in rep: rep[u] = M; queue.append(u)
            else: gens.add(mmul(minv(rep[u]), M))
    grp = {((1, 0), (0, 1))}; frontier = list(grp)
    while frontier:
        A = frontier.pop()
        for g in gens:
            Bm = mmul(A, g)
            if Bm not in grp:
                grp.add(Bm); frontier.append(Bm)
                if len(grp) > 5000: return len(rep), None
    return len(rep), sorted(mmul(minv(M0), mmul(A, M0)) for A in grp)   # conjugate back to w
if __name__ == "__main__":
    tests = [("c = xyxYYXy", "xyxYYXy"), ("b = xyxYXY", "xyxYXY")] + [("p_%d" % n, "x" * n + "Y" * (n + 1)) for n in range(2, 8)] \
        + [("k_%d" % n, "x" * n + "YXyy") for n in (3, 4)] + [("x^2yXy", "xxyXy"), ("[x,y]", "xyXY")]
    for name, w in tests:
        n1, S1 = stabilizer(w, True); n2, S2 = stabilizer(w, False)
        print("%-12s level-graph vertices %3d | Stab(w^+-1): %s | Stab(w): %s" % (name, n1, S1 if S1 is None or len(S1) <= 8 else len(S1), S2 if S2 is None or len(S2) <= 8 else len(S2)))
