def twist_scan(p, q, depth=7, box=40):
    lam = lambda v: q*v[0] - p*v[1]
    gens = [((1, p), (0, 1)), ((1, -p), (0, 1)), ((1, 0), (q, 1)), ((1, 0), (-q, 1)), ((-1, 0), (0, 1)), ((1, 0), (0, -1))]
    mm = lambda A, B: tuple(tuple(sum(A[i][k]*B[k][j] for k in range(2)) for j in range(2)) for i in range(2))
    I = ((1, 0), (0, 1)); seen = {I}; fr = [I]
    for _ in range(depth):
        nx = []
        for M in fr:
            for g in gens:
                N = mm(g, M)
                if N not in seen and max(abs(e) for r in N for e in r) < 10**6: seen.add(N); nx.append(N)
        fr = nx
    Lam = [(a, b) for a in range(-box, box+1) for b in range(-box, box+1) if abs(lam((a, b))) == 1]
    good = set()
    for M in seen:
        for v in Lam:
            w = (M[0][0]*v[0] + M[0][1]*v[1], M[1][0]*v[0] + M[1][1]*v[1])
            if abs(lam(w)) == 1: good.add(M); break
    return len(seen), len(Lam), sorted(good)
