#!/usr/bin/env python3
"""Group-triviality check and length-descent search for thickenable cases.

Research agent F, 2026-11-02.  Standard library only.

* `coset_index(rels, subgroup_gen, limit)`: HLT Todd-Coxeter coset
  enumeration of <x,y | rels> over the cyclic subgroup generated by one
  generator.  Index 1 together with perfectness (trivial abelianization)
  proves the group trivial.  This is a group-theory check only.

* `descend(r1, r2, K)`: greedy/beam search for a sequence of quotient-
  conjugacy ("ACM") replacements u <- CR(rot(u) * c * rot(v^e) * c^-1) with
  |c| <= K that strictly lower total cyclic length, ending at total length 2.
  Every step is then compiled into ORDINARY elementary AC moves
  (single-letter conjugations, inversions, right multiplications) in the
  repository's `ordinary-ac-elementary-v1` format, and the final pair is
  normalized to exactly (x, y).  The certificate is replayed by
  experiments/elementary_verify.py; nothing about thickenability is trusted.
"""
import itertools
import json
import os
import sys

