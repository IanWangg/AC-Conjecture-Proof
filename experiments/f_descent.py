import f_thicken as T  # noqa: E402

GENS = (1, -1, 2, -2)


# ------------------------------------------------------------ Todd-Coxeter

def coset_index(rels, sub=(1,), limit=200000):
    """Return the index of <sub> in <x,y|rels> or None if the coset limit
    is exceeded.  Simple HLT strategy with coincidence processing."""
    cols = {1: 0, -1: 1, 2: 2, -2: 3}
    table = [[None] * 4]
    parent = [0]

    def find(c):
        while parent[c] != c:
            parent[c] = parent[parent[c]]
            c = parent[c]
        return c

    def new_coset():
        if len(table) >= limit:
            raise OverflowError
        table.append([None] * 4)
        parent.append(len(table) - 1)
        return len(table) - 1

    def coincidence(a, b):
        queue = [(a, b)]
        while queue:
            a, b = queue.pop()
            a, b = find(a), find(b)
            if a == b:
                continue
            if a > b:
                a, b = b, a
            parent[b] = a
            for g in GENS:
                tb = table[b][cols[g]]
                if tb is None:
                    continue
                tb = find(tb)
                table[b][cols[g]] = None
                if table[tb][cols[-g]] is not None and find(table[tb][cols[-g]]) == b:
                    table[tb][cols[-g]] = None
                ta = table[a][cols[g]]
                if ta is None:
                    table[a][cols[g]] = tb
                    if table[tb][cols[-g]] is None:
                        table[tb][cols[-g]] = a
                    else:
                        queue.append((find(table[tb][cols[-g]]), a))
                else:
                    queue.append((find(ta), tb))

    def scan_and_fill(c, w):
        f, b = c, c
        i, j = 0, len(w) - 1
        while True:
            # forward scan
            while i <= j and table[find(f)][cols[w[i]]] is not None:
                f = find(table[find(f)][cols[w[i]]])
                i += 1
            if i > j:
                if find(f) != find(b):
                    coincidence(find(f), find(b))
                return
            # backward scan
            while j >= i and table[find(b)][cols[-w[j]]] is not None:
                b = find(table[find(b)][cols[-w[j]]])
                j -= 1
            if j < i:
                coincidence(find(f), find(b))
                return
            if i == j:
                f, b = find(f), find(b)
                table[f][cols[w[i]]] = b
                table[b][cols[-w[i]]] = f
                return
            # define a new coset
            f = find(f)
            n = new_coset()
            table[f][cols[w[i]]] = n
            table[n][cols[-w[i]]] = f

    allrels = [tuple(r) for r in rels]
    try:
        scan_and_fill(0, tuple(sub))
        c = 0
        while c < len(table):
            if find(c) == c:
                for r in allrels:
                    if find(c) != c:
                        break
                    scan_and_fill(c, r)
                if find(c) == c:
                    for g in GENS:
                        if table[c][cols[g]] is None:
                            n = new_coset()
                            table[c][cols[g]] = n
                            table[n][cols[-g]] = c
            c += 1
    except OverflowError:
        return None
    return sum(1 for c in range(len(table)) if find(c) == c)


def is_trivial_group(r1, r2, limit=200000):
    a = (sum(1 for c in r1 if c == 1) - sum(1 for c in r1 if c == -1),
         sum(1 for c in r1 if c == 2) - sum(1 for c in r1 if c == -2))
    b = (sum(1 for c in r2 if c == 1) - sum(1 for c in r2 if c == -1),
         sum(1 for c in r2 if c == 2) - sum(1 for c in r2 if c == -2))
    if abs(a[0] * b[1] - a[1] * b[0]) != 1:
        return False
    for sub in ((1,), (2,)):
        idx = coset_index([r1, r2], sub, limit)
        if idx == 1:
            return True
        if idx is not None and idx > 1:
            return False
    return None


# ------------------------------------------------------- ACM descent search

def rotations(w):
    return [w[k:] + w[:k] for k in range(len(w))]


def words_upto(K):
    out = [()]
    frontier = [()]
    for _ in range(K):
        nxt = []
        for w in frontier:
            for g in GENS:
                if w and w[-1] == -g:
                    continue
                nxt.append(w + (g,))
        out += nxt
        frontier = nxt
    return out


def acm_moves(state, K):
    """Yield (new_state, packaged_description) for replacements
    u <- CR(u * c v^e c^-1) with |c|<=K (u cyclically rotated first)."""
    conj = words_upto(K)
    for i in (0, 1):
        u, v = state[i], state[1 - i]
        for k in range(len(u)):
            ur = u[k:] + u[:k]
            for e in (1, -1):
                ve = v if e == 1 else T.inverse(v)
                for c in conj:
                    w = T.cyc_reduce(ur + c + ve + T.inverse(c))
                    if not w:
                        continue
                    new = [None, None]
                    new[i], new[1 - i] = w, v
                    yield tuple(new), (i, k, e, c)


def descend(r1, r2, K=4, beam=200, max_rounds=200):
    """Beam search for strictly length-decreasing ACM steps to total length 2."""
    start = (T.cyc_reduce(r1), T.cyc_reduce(r2))
    layer = {start: []}
    for _ in range(max_rounds):
        best = {}
        for st, path in layer.items():
            L = len(st[0]) + len(st[1])
            if L == 2:
                return st, path
            for new, desc in acm_moves(st, K):
                Ln = len(new[0]) + len(new[1])
                if Ln >= L:
                    continue
                key = (T.cyc_canon(new[0]), T.cyc_canon(new[1]))
                if key not in best or len(best[key][1]) > len(path) + 1:
                    best[key] = (new, path + [(st, desc, new)])
        if not best:
            return None
        items = sorted(best.values(), key=lambda t: len(t[0][0]) + len(t[0][1]))
        layer = {st: p for st, p in items[:beam]}
    return None


# ------------------------------------------------- compile to elementary AC

class Compiler:
    """Tracks an exact ordered state and emits strict elementary moves."""

    def __init__(self, r1, r2):
        self.s = [tuple(r1), tuple(r2)]
        self.moves = []

    def inv(self, i):
        self.s[i] = T.inverse(self.s[i])
        self.moves.append({"op": "invert", "i": i})

    def mul(self, i):
        j = 1 - i
        self.s[i] = T.free_reduce(self.s[i] + self.s[j])
        self.moves.append({"op": "multiply", "i": i, "j": j})

    def conj(self, i, g):
        self.s[i] = T.free_reduce((g,) + self.s[i] + (-g,))
        self.moves.append({"op": "conjugate", "i": i, "g": T.SYM[g]})

    def conj_word(self, i, c):
        """Replace s[i] by c s[i] c^-1 (freely reduced)."""
        for g in reversed(c):
            self.conj(i, g)

    def to_cyclic(self, i, target):
        """Conjugate s[i] until it equals `target`, a cyclically reduced word
        that is a rotation of the cyclic reduction of s[i]."""
        w = self.s[i]
        # strip: w = a z a^-1 with z cyclically reduced
        a = []
        while len(w) >= 2 and w[0] == -w[-1]:
            a.append(w[0])
            w = w[1:-1]
        # conjugate by a^-1: a^-1 (a z a^-1) a = z
        self.conj_word(i, T.inverse(tuple(a)))
        assert self.s[i] == w, (self.s[i], w)
        n = len(w)
        for k in range(n):
            if w[k:] + w[:k] == target:
                # rotate left by k: conjugate by (w[:k])^-1
                self.conj_word(i, T.inverse(w[:k]))
                assert self.s[i] == target
                return
        raise AssertionError("target is not a rotation")


def compile_path(r1, r2, path):
    C = Compiler(T.cyc_reduce(r1), T.cyc_reduce(r2))
    # ensure the starting relators are cyclically reduced exactly
    assert C.s == [T.cyc_reduce(r1), T.cyc_reduce(r2)]
    for (st, (i, k, e, c), new) in path:
        j = 1 - i
        assert tuple(C.s[i]) == st[i] and tuple(C.s[j]) == st[j]
        u, v = st[i], st[j]
        # rotate u to ur
        C.to_cyclic(i, u[k:] + u[:k])
        # make s[j] = c v^e c^-1
        if e == -1:
            C.inv(j)
        C.conj_word(j, c)
        C.mul(i)
        # restore s[j] = v
        C.conj_word(j, T.inverse(c))
        if e == -1:
            C.inv(j)
        assert tuple(C.s[j]) == v
        # cyclically reduce s[i] to the recorded new word (a rotation of it)
        C.to_cyclic(i, new[i])
    # normalize the final pair (length 2) to exactly (x, y)
    a, b = C.s
    assert len(a) == 1 and len(b) == 1 and abs(a[0]) != abs(b[0]), C.s
    if abs(a[0]) == 2:     # swap two single letters (a,b) -> (b,a):
        # (ab,b) (ab,B) (ab,Bab) (ab,a) (ab,A) (abA,A) (b,A) (b,a)
        A = -a[0]
        bl = b[0]
        C.mul(0)
        C.inv(1)
        C.mul(1)
        C.conj(1, bl)
        C.inv(1)
        C.mul(0)
        C.conj(0, A)
        C.inv(1)
        assert C.s == [b, a], C.s
    for i, g in ((0, 1), (1, 2)):
        if C.s[i] == (-g,):
            C.inv(i)
    assert C.s == [(1,), (2,)], C.s
    return C.moves


def certificate(r1, r2, K=4, beam=200):
    res = descend(r1, r2, K, beam)
    if res is None:
        return None
    _, path = res
    moves = compile_path(r1, r2, path)
    a, b = T.cyc_reduce(r1), T.cyc_reduce(r2)
    return {"format": "ordinary-ac-elementary-v1", "start": [T.fmt(a), T.fmt(b)],
            "target": ["x", "y"], "moves": moves,
            "description": f"AC trivialization of ({T.fmt(a)}, {T.fmt(b)}) found by "
                           f"strictly length-decreasing ACM descent (|c|<={K}), "
                           f"{len(path)} ACM steps, compiled to elementary moves"}


def selftest():
    P = T.parse
    assert is_trivial_group(P("x"), P("y"))
    assert is_trivial_group(P("xxxYYYY"), P("xyxYXY"))       # AK(3)
    assert is_trivial_group(P("xxyXy"), P("xyyyyxY")) is False  # nahomar's L=12 nontrivial
    import elementary_verify as V
    # a thickenable presentation of the trivial group: descent must succeed
    cert = certificate(P("xyxyxY"), P("xyxYxyyxY"), K=3)
    out = V.replay(json.loads(json.dumps(cert)))
    assert out["endpoint"] == ["x", "y"]
    # AK(3) has no strictly length-decreasing ACM step (research-a plateau)
    assert descend(P("xxxYYYY"), P("xyxYXY"), K=3, beam=50) is None
    print("self-test passed: Todd-Coxeter checks, descent certificate", out,
          "and AK(3) admits no strict descent step (K=3)")


def batch(path, maxlen=16):
    """Regenerate and replay descent certificates for every thickenable class
    (lines "LEN w1 w2 FLAG") of length <= maxlen whose flag is 1; also certify
    every thickenable flag-0 class as a nontrivial group."""
    import collections
    import elementary_verify as V
    cnt, peak = collections.Counter(), collections.defaultdict(int)
    nontriv, problems = 0, []
    for line in open(path):
        parts = line.split()
        L, a, b, flag = int(parts[0]), parts[1], parts[2], parts[3]
        if L > maxlen:
            continue
        r1, r2 = T.parse(a), T.parse(b)
        if not T.thickenable_fast(r1, r2):
            continue
        if flag == "0":
            if nontrivial_hom(r1, r2):
                nontriv += 1
            else:
                problems.append(("flag0-undecided", a, b))
            continue
        cert = certificate(r1, r2, K=2, beam=10) or certificate(r1, r2, K=3, beam=30)
        if cert is None:
            problems.append(("no-descent", a, b))
            continue
        out = V.replay(json.loads(json.dumps(cert)))
        assert out["endpoint"] == ["x", "y"]
        cnt[L] += 1
        peak[L] = max(peak[L], out["peak_total_length"])
    print(json.dumps({"certified_trivializations_by_length": dict(sorted(cnt.items())),
                      "max_peak_by_length": dict(sorted(peak.items())),
                      "thickenable_flag0_certified_nontrivial": nontriv,
                      "problems": problems}))


# ------------------------------------- nontriviality via permutation images

def _pmul(p, q):
    return tuple(q[i] for i in p)


def _pinv(p):
    r = [0] * len(p)
    for i, j in enumerate(p):
        r[j] = i
    return tuple(r)


def _cyc(n, cycles):
    p = list(range(n))
    for c in cycles:
        for i in range(len(c)):
            p[c[i]] = c[(i + 1) % len(c)]
    return tuple(p)


def _closure(gens):
    e = tuple(range(len(gens[0])))
    S, fr = {e}, [e]
    while fr:
        nf = []
        for a in fr:
            for g in gens:
                b = _pmul(a, g)
                if b not in S:
                    S.add(b)
                    nf.append(b)
        fr = nf
    return S


PERM_GROUPS = {   # name -> generators; orders are checked by closure
    "A5": [_cyc(5, [(0, 1, 2)]), _cyc(5, [(0, 1, 2, 3, 4)])],
    "A6": [_cyc(6, [(0, 1, 2)]), _cyc(6, [(1, 2, 3, 4, 5)])],
    "A7": [_cyc(7, [(0, 1, 2, 3, 4, 5, 6)]), _cyc(7, [(1, 2, 4), (3, 6, 5)]),
           _cyc(7, [(0, 1), (2, 3)])],
}


def nontrivial_hom(r1, r2, groups=("A5", "A6", "A7")):
    """Search a homomorphism F(x,y) -> G killing r1, r2 with nontrivial image.
    Returns (group name, order, (g, h)) or None.  A hit certifies that
    <x,y | r1, r2> is a nontrivial group."""
    for name in groups:
        G = sorted(_closure(PERM_GROUPS[name]))
        e = tuple(range(len(G[0])))
        # g may be taken up to simultaneous conjugation of (g, h): use class reps
        reps, covered = [], set()
        for g in G:
            if g not in covered:
                reps.append(g)
                covered |= {_pmul(_pmul(_pinv(k), g), k) for k in G}

        def ev(w, g, h):
            gi, hi = _pinv(g), _pinv(h)
            r = e
            for a in w:
                r = _pmul(r, {1: g, -1: gi, 2: h, -2: hi}[a])
            return r
        for g in reps:
            for h in G:
                if (g != e or h != e) and ev(r1, g, h) == e and ev(r2, g, h) == e:
                    return name, len(G), (g, h)
    return None


